                <h2>What is collected</h2>

                <h3>Server logs</h3>
                <p>The web server records each request: date and time, requested page, referrer, browser user agent and the IP address of the connection. Logs are used to keep the site running and secure, and are deleted after 14 days.</p>

                <h3>Cloudflare</h3>
                <p>Every request passes through <a href="https://www.cloudflare.com/privacypolicy/">Cloudflare</a>, which delivers the pages from a server close to you and protects the site from abuse. To do so, Cloudflare processes your IP address and the details of the request.</p>

                <h3>Visit statistics</h3>
                <p>The site counts visits with <a href="https://www.cloudflare.com/web-analytics/">Cloudflare Web Analytics</a>. It does not use cookies or local storage and does not build a profile of you: I only see aggregated figures, such as the most read pages, referring sites, countries and device types.</p>

                <h3>Documentation search</h3>
                <p>When you search the documentation, your browser sends the search text to <a href="https://www.algolia.com/policies/privacy/">Algolia</a>, which returns the results. Algolia also receives your IP address as part of the request. Nothing is sent until you type in the search box.</p>

                <h3>Theme preference</h3>
                <p>If you switch between the light and dark theme, your choice is saved in your browser's local storage. It never leaves your device.</p>

                <h3>Email</h3>
                <p>If you write to me, I use your address and your message only to reply.</p>

                <h2>Where the data goes</h2>
                <p>The site is hosted by OVHcloud on a server in Singapore. Cloudflare and Algolia are based in the United States. Transfers outside the European Union rely on the safeguards provided by the GDPR, such as the European Commission's standard contractual clauses.</p>

